poin = 100
print("Nilai awal :", poin)

#Tambahkan 25 poin menggunakan +=.
poin += 25
print("poin += 25 :", poin)

#Kurangi 10 poin menggunakan -=.
poin -= 10
print("poin -= 10 :", poin)

#Kalikan poin dengan 2 menggunakan *=.
poin *= 2
print ("poin *= 2 :", poin)

#Bagi poin dengan 2 menggunakan /=.
poin /= 2
print("poin /=    :", poin)





